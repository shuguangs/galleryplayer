"""Lightweight i18n for the player UI.

Language switching:
- config key ``language`` holds "zh" or "en" (default "zh").
- ``t(key)`` looks the active language up in ``_TR``; missing keys fall back
  to zh, then to the key itself so gaps are visible while developing.
- ``LANGUAGES`` feeds the language combo in the settings dialog.

The translation table is the single ``_TR`` dict at the bottom of this module.
UI code never holds language-specific strings inline anymore.
"""
from __future__ import annotations

from .config import settings

LANGUAGES: list[tuple[str, str]] = [
    ("zh", "中文"),
    ("en", "English"),
]


def current_language() -> str:
    lang = str(settings["language"] or "zh")
    return lang if lang in ("zh", "en") else "zh"


def set_language(code: str) -> None:
    settings["language"] = code


def t(key: str) -> str:
    entry = _TR.get(key)
    if not entry:
        return key
    return entry.get(current_language()) or entry.get("zh") or key


